from abc import abstractmethod
import copy
import random
import pickle


class Transaction(dict):
    """
    Transaction class is a customized `dict`.
    Each transaction stores the data of a single step in the environment, single agent or multi-agent.
    """
    def __init__(self, *args, **kwargs):
        self.multi_agent = kwargs.pop('multi_agent', False)
        super().__init__(*args, **kwargs)

    def get_agents(self):
        if self.multi_agent:
            return self.keys()
        else:
            return None
        
    def get_data(self, field, agent=None):
        if self.multi_agent:
            return self[agent][field]
        else:
            return self[field]

class Episode(list):
    """
    Episode class is a original `list`, write for readability.
    each data is a dict of {"transaction": Transaction, "index_in_episode": int}
    Episode is generated by BaseAlgorithm.rollout.
    """
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)

class Batch(list):
    """
    Batch class is a customized `list`.
    each transition is a dict of {"transaction": Transaction, "index_in_episode": int, ,"episode_index": int}.
    Batch is sampled from ReplayBuffer.
    """
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)

    def shuffle(self):
        random.shuffle(self)
        return self

class ReplayBuffer(list):
    """
    ReplayBuffer class is a customized `list` with max length.
    Each transition is a dict of {"transaction": Transaction, "index_in_episode": int, "episode_index": int}
    """
    def __init__(self, max_length=None):
        super().__init__()
        self.max_length = max_length
        self.episode_index = 0

    def sample(self, batch_size):
        return Batch(copy.deepcopy(random.sample(self, batch_size)))
    
    def insert_episode(self, episode):
        length_now = len(self)
        length_to_add = len(episode)
        if self.max_length is not None:
            if length_now + length_to_add > self.max_length:
                length_to_remove = length_now + length_to_add - self.max_length
                del self[:length_to_remove]
        self.extend(map(lambda x: dict(x, episode_index=self.episode_index), episode))
        self.episode_index += 1

    @abstractmethod
    def reload_from(path):
        with open(path, 'rb') as f:
            return pickle.load(f)
    
    def save(self, path):
        with open(path, 'wb') as f:
            pickle.dump(self, f)
